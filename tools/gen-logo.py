#!/usr/bin/env python3
"""Logo pipeline: firmware/assets/logo.png (square RGB/RGBA PNG) -> firmware/src/logo_data.h + web/assets/logo.png.
If the file is missing a default Peep meme miner eye mark is generated. Replace the PNG with your own and rebuild."""
import os, struct, sys, zlib

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
SRC = os.path.join(ROOT, 'firmware', 'assets', 'logo.png')
HDR = os.path.join(ROOT, 'firmware', 'src', 'logo_data.h')
WEB = os.path.join(ROOT, 'web', 'assets', 'logo.png')

def png_rgb(w, h, px):
    raw = b''.join(b'\x00' + bytes(sum(([r, g, b] for r, g, b in px[y * w:(y + 1) * w]), [])) for y in range(h))
    def chunk(t, d):
        c = struct.pack('>I', len(d)) + t + d
        return c + struct.pack('>I', zlib.crc32(t + d) & 0xffffffff)
    return b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 2, 0, 0, 0)) + \
        chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b'')

def default_logo(n=86):
    bg, ring, white, iris, pupil = (6, 8, 12), (31, 217, 154), (240, 247, 250), (31, 217, 154), (4, 20, 16)
    px, c = [], (n - 1) / 2.0
    for y in range(n):
        for x in range(n):
            dx, dy = (x - c) / c, (y - c) / c
            col = bg
            if dx * dx + dy * dy <= 1.0:
                col = (14, 24, 26)
                if dx * dx + dy * dy >= 0.80: col = ring            # outer ring
                ex = dx * dx / 0.62 + dy * dy / 0.22               # eye (ellipse)
                if ex <= 1.0:
                    col = white
                    r2 = dx * dx + dy * dy
                    if r2 <= 0.17: col = iris
                    if r2 <= 0.05: col = pupil
                    if (dx + 0.10) ** 2 + (dy + 0.10) ** 2 <= 0.006: col = white   # highlight
            px.append(col)
    return png_rgb(n, n, px)

os.makedirs(os.path.dirname(SRC), exist_ok=True)
if not os.path.exists(SRC):
    open(SRC, 'wb').write(default_logo())
    print('generated default logo:', SRC)
data = open(SRC, 'rb').read()
if data[:8] != b'\x89PNG\r\n\x1a\n':
    sys.exit('logo.png is not a PNG')
web_data = data
# Stick image: flatten transparency onto the card background (black) and make it square RGB.
try:
    from PIL import Image
    import io
    im = Image.open(io.BytesIO(data)).convert('RGBA')
    side = max(im.size)
    canvas = Image.new('RGBA', (side, side), (0, 0, 0, 255))
    canvas.alpha_composite(im, ((side - im.width) // 2, (side - im.height) // 2))
    rgb = canvas.convert('RGB')
    if side > 96:
        rgb = rgb.resize((96, 96), Image.LANCZOS)
    buf = io.BytesIO()
    rgb.save(buf, 'PNG', optimize=True)
    data = buf.getvalue()
except ImportError:
    print('note: Pillow not installed; using the PNG as is (transparent areas may look odd)')
w, h = struct.unpack('>II', data[16:24])
if len(data) > 20000:
    sys.exit('logo.png is %d bytes; keep it under 20 KB (e.g. 86x86)' % len(data))
body = ',\n  '.join(', '.join('0x%02x' % b for b in data[i:i + 16]) for i in range(0, len(data), 16))
open(HDR, 'w').write('// generated by tools/gen-logo.py: do not edit\n#pragma once\n#include <stdint.h>\n'
                     '#include <stddef.h>\nstatic const int LOGO_W = %d;\nstatic const int LOGO_H = %d;\n'
                     'static const size_t LOGO_PNG_LEN = %d;\nstatic const uint8_t LOGO_PNG[] = {\n  %s\n};\n' % (w, h, len(data), body))
os.makedirs(os.path.dirname(WEB), exist_ok=True)
open(WEB, 'wb').write(web_data)
print('logo %dx%d, %d bytes -> %s, %s' % (w, h, len(data), os.path.relpath(HDR, ROOT), os.path.relpath(WEB, ROOT)))
